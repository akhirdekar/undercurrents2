import fs from 'node:fs';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {summarize,dayCounts,dateWindow,metricValue,centerOf,HEX_RADIUS} from '../dist/logic.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=n=>JSON.parse(fs.readFileSync(path.join(root,'dist/data',n+'.json'),'utf8'));
const basins=read('basins'),reports=read('reports'),manifest=read('manifest'),rain=read('rainfall');
const state={borough:0,category:-1,start:manifest.profiles.date_range[0],end:manifest.profiles.date_range[1]};
const all=summarize(basins,reports,state);
assert.equal(all.assets.length,154212);assert.equal(all.reports.length,58965);
assert.equal(all.bins.reduce((s,b)=>s+b.basins,0),basins.length);
assert.equal(all.bins.reduce((s,b)=>s+b.reports,0),reports.length);
assert.equal(new Set(basins.map(r=>r[0])).size,basins.length);
assert.equal(new Set(reports.map(r=>r[0])).size,reports.length);
assert.ok(basins.every(r=>r[0].startsWith('CB')));
assert.ok(reports.every(r=>/^\d+$/.test(r[0])&&/^\d{4}-\d{2}-\d{2}$/.test(r[9])));
const queens=summarize(basins,reports,{...state,borough:4});
assert.equal(queens.assets.length,66387);assert.equal(queens.reports.length,23910);
const flooding=summarize(basins,reports,{...state,category:0});
assert.equal(flooding.reports.length,44058);assert.equal(flooding.assets.length,basins.length);
const single=summarize(basins,reports,{...state,start:'2021-09-02',end:'2021-09-02'});
assert.ok(single.reports.length>0);assert.ok(single.reports.every(r=>r[9]==='2021-09-02'));
assert.equal(single.assets.length,basins.length,'Inventory must not change when dates change');
const none=summarize(basins,reports,{...state,start:'2019-01-01',end:'2019-01-01'});
assert.equal(none.reports.length,0);assert.equal(none.assets.length,basins.length);
const fixture=summarize([], [['1',0,0,4,0,0,0,0,0,'2021-01-01']],{...state,start:'2021-01-01',end:'2021-01-01'});
assert.equal(metricValue(fixture.bins[0],'ratio'),null,'No denominator must be unavailable, not zero');
const daily=dayCounts(reports,state,rain.map(r=>r[0]));
assert.equal(daily.reduce((s,r)=>s+r[1],0),reports.length);
assert.deepEqual(dayCounts(reports,{...state,start:'2021-09-02',end:'2021-09-02'},rain.map(r=>r[0])),daily,'Timeline context ignores active date range while respecting other filters');
assert.deepEqual(dateWindow('2021-09-02'),['2021-08-31','2021-09-06']);
assert.ok(Math.abs(3*Math.sqrt(3)/2*HEX_RADIUS**2-1e6)<1e-6);
assert.ok(all.bins.every(b=>centerOf(b.q,b.r).every(Number.isFinite)));
for(const [r,type] of [[basins,'basin'],[reports,'report']])for(const row of r){
  const [x,y]=centerOf(row[6],row[7]);assert.ok(Math.hypot(x-row[4],y-row[5])<=HEX_RADIUS+.2,type+' lies within assigned hex');
}
assert.equal(rain.length,2401);assert.ok(rain.every(r=>r[1]===null||r[1]>=0));
const html=fs.readFileSync(path.join(root,'dist/index.html'),'utf8');
const app=fs.readFileSync(path.join(root,'dist/app.mjs'),'utf8');
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);assert.equal(new Set(ids).size,ids.length,'HTML IDs must be unique');
const dynamic=new Set(['street-zoom']);
for(const m of app.matchAll(/\$\('([^']+)'\)/g))assert.ok(ids.includes(m[1])||dynamic.has(m[1]),'Missing UI element '+m[1]);
for(const f of ['vendor/d3.min.js','app.mjs','logic.mjs','styles.css','data/manifest.json','data/cleaning_audit.csv','data/enriched_complaints.csv'])assert.ok(fs.statSync(path.join(root,'dist',f)).isFile());
console.log(JSON.stringify({result:'PASS',basins:basins.length,reports:reports.length,grid_cells:all.bins.length,single_day_reports:single.reports.length,checked:'conservation of totals; filter combinations; ID separation; fixed denominator; no-data ratio; day aggregation; hex area and membership; rainfall values; HTML references and required assets',browser_visual_QA:'Separate browser checks documented in README.md'},null,2));
